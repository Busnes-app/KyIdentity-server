import type { WorkstationApp } from './types';

/** Himmelblau drops group claims containing ':'; a ',' would split the allow list. */
export function unusableGroups(groups: string[]): string[] {
  return groups.filter(g => g.includes(':') || g.includes(',') || g.trim() !== g || g === '');
}

/**
 * The himmelblau.conf for a workstation app (Himmelblau generic OIDC mode). The issuer must
 * be HTTPS and match discovery exactly; pam_allow_groups names the app's assigned groups,
 * which reach Himmelblau through the userinfo groups claim (Himmelblau 4.0+).
 */
export function himmelblauConf(issuer: string, app: WorkstationApp): string {
  const usable = app.groups.filter(g => !unusableGroups([g]).length);
  const lines = [
    `# himmelblau.conf for "${app.clientName.replace(/[\r\n]/g, ' ')}", generated by KyIdentity`,
    '[global]',
    `oidc_issuer_url = ${issuer}`,
    `app_id = ${app.clientId}`,
  ];
  if (usable.length) {
    lines.push('# Only members of these KyIdentity groups may sign in (needs Himmelblau 4.0 or later).');
    lines.push(`pam_allow_groups = ${usable.join(',')}`);
  } else {
    lines.push('# No groups are assigned: everyone KyIdentity lets into this app may sign in.');
  }
  return lines.join('\n') + '\n';
}

/** Seconds to whole days, for the offline window field. */
export const days = (seconds: number) => Math.round(seconds / 86400);
