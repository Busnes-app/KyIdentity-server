import { describe, expect, it } from 'vitest';
import { himmelblauConf, unusableGroups } from './workstation';

const app = { clientId: 'c-1', clientName: 'Office\nPCs', appId: 'a', enabled: true, deviceGrantEnabled: true, deviceCodeTtl: 300, offlineWindow: 604800, groups: ['linux-users', 'ops:admins', 'eng'] };

describe('himmelblauConf', () => {
  it('names the issuer, the client and only the usable groups', () => {
    const conf = himmelblauConf('https://id.example.com', app);
    expect(conf).toContain('oidc_issuer_url = https://id.example.com\n');
    expect(conf).toContain('app_id = c-1\n');
    expect(conf).toContain('pam_allow_groups = linux-users,eng\n');
    expect(conf).not.toContain('ops:admins');
    expect(conf.split('\n')[0]).toBe('# himmelblau.conf for "Office PCs", generated by KyIdentity');
  });
  it('omits pam_allow_groups with no usable group', () => {
    expect(himmelblauConf('https://id.example.com', { ...app, groups: [] })).not.toContain('pam_allow_groups =');
  });
  it('flags names Himmelblau cannot match', () => {
    expect(unusableGroups(['a:b', 'a,b', ' a', 'ok'])).toEqual(['a:b', 'a,b', ' a']);
  });
});
