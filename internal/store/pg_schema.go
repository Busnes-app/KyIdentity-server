// The Postgres version-1 schema: what migrateLegacy produces on SQLite, written once by
// hand. Column names match SQLite's exactly (TestBackendsHaveTheSameColumns); types are
// chosen so the shared SQL runs unchanged: BOOLEAN for SQLite's BOOLEAN columns (Postgres
// refuses an integer where a condition is expected, and the shared SQL tests them bare),
// TIMESTAMPTZ for DATETIME, BIGINT for every integer, CITEXT for COLLATE NOCASE on a
// C-locale database, an identity column named rowid where the SQL orders by rowid. It is
// applied with its schema_migrations row in one transaction. Never edit it once shipped:
// later changes are migrations with a Postgres body.

